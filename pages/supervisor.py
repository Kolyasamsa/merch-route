from datetime import date
from datetime import timedelta

import pandas as pd

import streamlit as st


from database import (
    get_completed_visits_for_period,
)


from utils import (
    MONTHS,
    format_date_short,
)


# =========================================================
# НАСТРОЙКИ
# =========================================================

st.set_page_config(

    page_title="Табель",

    page_icon="📊",

    layout="wide",

)


# =========================================================
# ЗАГОЛОВОК
# =========================================================

st.title(
    "📊 Табель мерчендайзеров"
)


st.caption(
    "Количество пройденных торговых точек"
)


# =========================================================
# ТЕКУЩАЯ ДАТА
# =========================================================

today = date.today()


# =========================================================
# ВЫБОР ГОДА
# =========================================================

year_options = [

    today.year - 1,

    today.year,

    today.year + 1,

]


year = st.selectbox(

    "📅 Год",

    year_options,

    index=1,

)


# =========================================================
# ВЫБОР МЕСЯЦА
# =========================================================

month_name = st.selectbox(

    "📅 Месяц",

    MONTHS,

    index=today.month - 1,

)


month = (

    MONTHS.index(
        month_name
    )

    + 1

)


# =========================================================
# НАЧАЛО И КОНЕЦ МЕСЯЦА
# =========================================================

start_date = date(

    year,

    month,

    1,

)


if month == 12:


    next_month = date(

        year + 1,

        1,

        1,

    )


else:


    next_month = date(

        year,

        month + 1,

        1,

    )


end_date = (

    next_month

    - timedelta(
        days=1
    )

)


start_date_string = (

    start_date.strftime(
        "%Y-%m-%d"
    )

)


end_date_string = (

    end_date.strftime(
        "%Y-%m-%d"
    )

)


# =========================================================
# ЗАГРУЗКА ДАННЫХ
# =========================================================

try:


    visits = (

        get_completed_visits_for_period(

            start_date_string,

            end_date_string,

        )

    )


except Exception as error:


    st.error(

        f"Ошибка загрузки табеля: "
        f"{error}"

    )


    st.stop()


# =========================================================
# ВСЕ ДНИ МЕСЯЦА
# =========================================================

all_dates = []


current_date = start_date


while current_date <= end_date:


    all_dates.append(
        current_date
    )


    current_date += timedelta(
        days=1
    )


# =========================================================
# ЕСЛИ ДАННЫХ НЕТ
# =========================================================

if not visits:


    st.info(
        "За выбранный месяц "
        "прохождений пока нет."
    )


    st.stop()


# =========================================================
# DATAFRAME ИЗ SUPABASE
# =========================================================

df = pd.DataFrame(
    visits
)


# =========================================================
# ПРИВОДИМ ДАТУ
# =========================================================

df[
    "visit_date"
] = pd.to_datetime(

    df[
        "visit_date"
    ]

)


# =========================================================
# ГРУППИРУЕМ ТТ
# =========================================================

table = pd.crosstab(

    df[
        "worker"
    ],

    df[
        "visit_date"
    ].dt.date,

)


# =========================================================
# ДОБАВЛЯЕМ ВСЕ ДНИ МЕСЯЦА
# =========================================================

for current_day in all_dates:


    if current_day not in table.columns:

        table[
            current_day
        ] = 0


# =========================================================
# СОРТИРУЕМ ДНИ
# =========================================================

table = table[
    all_dates
]


# =========================================================
# ПЕРЕИМЕНОВЫВАЕМ СТОЛБЦЫ
# =========================================================

table.columns = [

    format_date_short(
        current_day
    )

    for current_day
    in all_dates

]


# =========================================================
# ИТОГО
# =========================================================

table[
    "ИТОГО"
] = table.sum(
    axis=1
)


# =========================================================
# МЕРЧЕНДАЙЗЕР В ОТДЕЛЬНЫЙ СТОЛБЕЦ
# =========================================================

table = (

    table
    .reset_index()

)


table = table.rename(

    columns={

        "worker":
            "Мерчендайзер"

    }

)


# =========================================================
# ПОКАЗЫВАЕМ
# =========================================================

st.subheader(

    f"📅 {month_name} {year}"

)


st.dataframe(

    table,

    use_container_width=True,

    hide_index=True,

)
