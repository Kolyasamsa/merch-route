from pathlib import Path

import pandas as pd

from config import DAYS


# =========================================================
# ПУТЬ К EXCEL-ФАЙЛУ
# =========================================================

ROUTES_FILE = Path(
    "routes.xlsx"
)


# =========================================================
# ЗАГРУЗКА МАРШРУТОВ
# =========================================================

def load_routes():

    # -----------------------------------------------------
    # ПРОВЕРЯЕМ НАЛИЧИЕ ФАЙЛА
    # -----------------------------------------------------

    if not ROUTES_FILE.exists():

        raise FileNotFoundError(

            f"Не найден файл маршрутов: "
            f"{ROUTES_FILE}"
        )


    # -----------------------------------------------------
    # ЗАГРУЖАЕМ EXCEL
    # -----------------------------------------------------

    df = pd.read_excel(
        ROUTES_FILE
    )


    # -----------------------------------------------------
    # ОБЯЗАТЕЛЬНЫЕ КОЛОНКИ
    # -----------------------------------------------------

    required_columns = [

        "Мерчендайзер",

        "Маршрут",

        "День",

        "Магазин",

        "Адрес",
    ]


    missing_columns = [

        column

        for column in required_columns

        if column not in df.columns
    ]


    if missing_columns:

        raise ValueError(

            "В routes.xlsx отсутствуют колонки: "

            + ", ".join(
                missing_columns
            )
        )


    # -----------------------------------------------------
    # УБИРАЕМ ПУСТЫЕ СТРОКИ
    # -----------------------------------------------------

    df = df.dropna(

        how="all"

    )


    # -----------------------------------------------------
    # ПРИВОДИМ ТЕКСТОВЫЕ КОЛОНКИ В ПОРЯДОК
    # -----------------------------------------------------

    text_columns = [

        "Мерчендайзер",

        "Маршрут",

        "День",

        "Магазин",

        "Адрес",
    ]


    for column in text_columns:

        df[column] = (

            df[column]

            .fillna("")

            .astype(str)

            .str.strip()
        )


    # -----------------------------------------------------
    # УБИРАЕМ СТРОКИ БЕЗ ОСНОВНЫХ ДАННЫХ
    # -----------------------------------------------------

    df = df[

        (df["Мерчендайзер"] != "")

        &

        (df["Маршрут"] != "")

        &

        (df["День"] != "")

        &

        (df["Магазин"] != "")

        &

        (df["Адрес"] != "")

    ].copy()


    return df


# =========================================================
# ПОЛУЧЕНИЕ ВСЕХ МЕРЧЕНДАЙЗЕРОВ
# =========================================================

def get_workers(
    df,
):

    workers = (

        df["Мерчендайзер"]

        .dropna()

        .unique()

        .tolist()
    )


    return sorted(
        workers
    )


# =========================================================
# ДАННЫЕ КОНКРЕТНОГО МЕРЧЕНДАЙЗЕРА
# =========================================================

def get_worker_data(
    df,
    worker,
):

    worker_data = (

        df[

            df["Мерчендайзер"]

            == worker

        ]

        .copy()
    )


    return worker_data


# =========================================================
# ДОСТУПНЫЕ ДНИ МЕРЧЕНДАЙЗЕРА
# =========================================================

def get_available_days(
    worker_data,
):

    worker_days = (

        worker_data["День"]

        .dropna()

        .unique()

        .tolist()
    )


    # -----------------------------------------------------
    # СОХРАНЯЕМ ПРАВИЛЬНЫЙ ПОРЯДОК ДНЕЙ НЕДЕЛИ
    # -----------------------------------------------------

    ordered_days = [

        day

        for day in DAYS

        if day in worker_days
    ]


    return ordered_days


# =========================================================
# МАРШРУТЫ НА КОНКРЕТНЫЙ ДЕНЬ
# =========================================================

def get_routes_for_day(
    worker_data,
    day,
):

    # -----------------------------------------------------
    # ФИЛЬТРУЕМ ПО ДНЮ
    # -----------------------------------------------------

    day_data = (

        worker_data[

            worker_data["День"]

            == day

        ]

        .copy()
    )


    # -----------------------------------------------------
    # ПОЛУЧАЕМ УНИКАЛЬНЫЕ МАРШРУТЫ
    # -----------------------------------------------------

    routes = (

        day_data["Маршрут"]

        .dropna()

        .unique()

        .tolist()
    )


    return (

        day_data,

        routes,
    )
